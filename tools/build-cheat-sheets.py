#!/usr/bin/env python3
"""Regenerate docs/appendix/e-cheat-sheets.md from every chapter's closing
'!!! abstract "Cheat Sheet"' admonition. Run after editing any chapter."""
import pathlib

PARTS = [("Platform","01-platform"),("Language","02-language"),("Collections","03-collections"),
         ("Concurrency","04-concurrency"),("Runtime","05-runtime"),("Testing","06-testing")]
root = pathlib.Path(__file__).resolve().parent.parent
out = ["---","title: Cheat Sheet Index","status: review","---","",
       "# Appendix E — Cheat Sheet Index","",
       "Every chapter closes with a cheat sheet. This page collects all of them, in handbook "
       "order, as a single-page review. Each heading links to the full chapter.","",
       "!!! tip \"How to use this page\"",
       "    Read a part's cheat sheets before an interview or a design review. Anything you "
       "cannot explain from the one-line summary is a signal to reread that chapter's Internals section.","",
       "!!! note \"Generated\"",
       "    This page is generated by `tools/build-cheat-sheets.py`. Edit the chapters, not this file.",""]
n = 0
for part, d in PARTS:
    out += [f"## {part}", ""]
    for f in sorted(p for p in (root/"docs"/d).glob("*.md") if p.name != "index.md"):
        lines = f.read_text().splitlines()
        title = next((l[2:].strip() for l in lines if l.startswith("# ")), f.stem)
        start = next(i for i,l in enumerate(lines) if l.strip().startswith('!!! abstract "Cheat Sheet"'))
        items = []
        for l in lines[start+1:]:
            if l.startswith("    ") or not l.strip():
                if l.strip(): items.append(l.strip())
            else:
                break
        out += [f"### {f.name.split('-')[0]} · [{title}](../{d}/{f.name})", ""]
        out += [f"- {it}" for it in items] + [""]
        n += 1
(root/"docs/appendix/e-cheat-sheets.md").write_text("\n".join(out) + "\n")
print(f"collected {n} cheat sheets")
